"""Make src/decks/constellation-data.ts: the real star patterns for Infinity & Beyond's Night Sky.

Source: the d3-celestial package by Olaf Frohn (BSD-3-Clause licence), whose star positions and
constellation lines come from the Yale Bright Star Catalogue. Get it with npm and point this
script at its data folder:

    npm pack d3-celestial@0.7.35 && tar -xzf d3-celestial-0.7.35.tgz
    python3 scripts/constellations-from-celestial.py package/data src/decks/constellation-data.ts

Each constellation is projected on its own, as seen looking up at the sky (north up, east to the
LEFT, which is why star charts look mirrored next to maps), and scaled to fit a circle of radius 1.
"""
import json
import math
import sys

# Game item id -> IAU abbreviation used by d3-celestial.
WANTED = {
    "aries": "Ari", "taurus": "Tau", "gemini": "Gem", "cancer": "Cnc", "leo": "Leo", "virgo": "Vir",
    "libra": "Lib", "scorpius": "Sco", "ophiuchus": "Oph", "sagittarius": "Sgr", "capricornus": "Cap",
    "aquarius": "Aqr", "pisces": "Psc", "orion": "Ori", "ursamajor": "UMa", "crux": "Cru",
    "cassiopeia": "Cas",
}


def unit(ra, dec):
    a, d = math.radians(ra), math.radians(dec)
    return (math.cos(d) * math.cos(a), math.cos(d) * math.sin(a), math.sin(d))


def main(data_dir, out_path):
    lines = {f["id"]: f["geometry"]["coordinates"] for f in json.load(open(f"{data_dir}/constellations.lines.json"))["features"]}
    stars = [(f["geometry"]["coordinates"], f["properties"]["mag"]) for f in json.load(open(f"{data_dir}/stars.6.json"))["features"]]

    def magnitude(ra, dec):
        best, mag = 1e9, 5.0
        for (sra, sdec), m in stars:
            if abs(sdec - dec) > 0.2:
                continue
            dra = (sra - ra + 180) % 360 - 180
            dist = (dra * math.cos(math.radians(dec))) ** 2 + (sdec - dec) ** 2
            if dist < best:
                best, mag = dist, m
        return mag if best < 0.04 else 5.0

    out = []
    for game_id, iau in WANTED.items():
        polylines = lines[iau]
        points, index, segs = [], {}, []
        for pl in polylines:
            prev = None
            for ra, dec in pl:
                key = (round(ra, 3), round(dec, 3))
                if key not in index:
                    index[key] = len(points)
                    points.append((ra, dec))
                i = index[key]
                if prev is not None and prev != i:
                    segs.append((prev, i))
                prev = i
        # Centre: the average direction of the stars.
        vx = sum(unit(*p)[0] for p in points); vy = sum(unit(*p)[1] for p in points); vz = sum(unit(*p)[2] for p in points)
        a0 = math.atan2(vy, vx); d0 = math.atan2(vz, math.hypot(vx, vy))
        xy = []
        for ra, dec in points:
            a, d = math.radians(ra), math.radians(dec)
            c = math.sin(d0) * math.sin(d) + math.cos(d0) * math.cos(d) * math.cos(a - a0)
            x = math.cos(d) * math.sin(a - a0) / c
            y = (math.cos(d0) * math.sin(d) - math.sin(d0) * math.cos(d) * math.cos(a - a0)) / c
            xy.append((-x, -y))  # east to the left, north up (SVG y grows downwards)
        cx = (max(p[0] for p in xy) + min(p[0] for p in xy)) / 2
        cy = (max(p[1] for p in xy) + min(p[1] for p in xy)) / 2
        r = max(math.hypot(x - cx, y - cy) for x, y in xy) or 1
        pts = [[round((x - cx) / r, 3), round((y - cy) / r, 3), round(magnitude(*points[i]), 1)] for i, (x, y) in enumerate(xy)]
        out.append((game_id, iau, pts, segs))

    with open(out_path, "w") as f:
        f.write("// GENERATED by scripts/constellations-from-celestial.py. Do not edit by hand.\n")
        f.write("// Real star patterns for the Night Sky stage. Star positions and lines: d3-celestial by\n")
        f.write("// Olaf Frohn (BSD-3-Clause), from the Yale Bright Star Catalogue.\n")
        f.write("// Each pattern fits a circle of radius 1, north up and east to the left, as seen looking up.\n")
        f.write("// stars: [x, y, magnitude] (smaller magnitude = brighter); lines: pairs of star indexes.\n\n")
        f.write("export interface StarPattern { stars: [number, number, number][]; lines: [number, number][] }\n\n")
        f.write("export const PATTERNS: Record<string, StarPattern> = {\n")
        for game_id, iau, pts, segs in out:
            f.write(f"  // {iau}\n  {game_id}: {{\n    stars: {json.dumps(pts)},\n    lines: {json.dumps([list(s) for s in segs])},\n  }},\n")
        f.write("};\n")
    print(f"wrote {len(out)} patterns to {out_path}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
